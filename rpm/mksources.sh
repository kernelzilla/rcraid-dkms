#!/bin/bash
# mksources.sh - build the source tarball expected by rcraid-dkms.spec.
#
# Usage:  rpm/mksources.sh [outdir]
#   outdir  directory to write rcraid-dkms-<version>.tar.gz to
#           (default: current directory)
#
# The tarball contains the kernel module sources in flat layout plus the
# dkms.conf template and the SDK license, i.e. everything DKMS needs to
# build the module on the target machine.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
OUTDIR="${1:-.}"

VERSION="$(awk '/^Version:/ {print $2; exit}' "$HERE/rcraid-dkms.spec")"
NAME="rcraid-dkms-$VERSION"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
PKGDIR="$STAGE/$NAME"
mkdir -p "$PKGDIR"

# Driver sources. Copy by glob so generated build artifacts
# (*.o, *.cmd, Module.symvers, vers.c, .tmp_versions, ...) never leak in.
cd "$ROOT/src"
cp -a Makefile *.h rcblob.x86_64 common_shell install_rh uninstall_rh "$PKGDIR/"
for f in *.c; do
    case "$f" in
        vers.c|rcraid.mod.c) ;;   # generated by the build, never shipped
        *) cp -a "$f" "$PKGDIR/" ;;
    esac
done

# DKMS descriptor (template - @DKMS_VERSION@ is substituted by rpmbuild)
# and the license.
cp "$HERE/dkms.conf"   "$PKGDIR/dkms.conf"
cp "$ROOT/LICENSE_SDK" "$PKGDIR/LICENSE_SDK"

# Normalize permissions: plain source files, nothing executable.
chmod -R u+rwX,go+rX,go-w "$PKGDIR"
find "$PKGDIR" -type f -exec chmod 644 {} +

mkdir -p "$OUTDIR"
tar -C "$STAGE" -czf "$OUTDIR/$NAME.tar.gz" "$NAME"
echo "$OUTDIR/$NAME.tar.gz"
